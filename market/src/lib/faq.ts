export function guessFaqCategory(q: string): FaqCategoryId {
  if (/ارسال|سفارش|پیگیری|آدرس|پیک|پست|آماده‌سازی|آماده/.test(q)) return "shipping";
  if (/مرجوع|گارانتی|اصالت|تعویض|بازگشت/.test(q)) return "returns";
  if (/پرداخت|فاکتور|تخفیف|درگاه|تراکنش|پول/.test(q)) return "payment";
  if (/دیجیتال|دانلود|لایسنس|نرم‌افزار|فایل/.test(q)) return "digital";
  if (/فنی|قطعه|سازگار|دیتاشیت|برد|سنسور|راه‌اندازی|نماینده/.test(q)) return "technical";
  return "account";
}

export function mergeFaqs(fromDb: { q: string; a: string }[]): FaqItem[] {
  const byQ = new Map<string, FaqItem>();
  for (const item of DEFAULT_FAQS) byQ.set(item.q.trim(), item);
  fromDb.forEach((item, i) => {
    const q = item.q?.trim();
    if (!q) return;
    const existing = byQ.get(q);
    if (existing) {
      byQ.set(q, { ...existing, a: item.a?.trim() || existing.a });
    } else {
      byQ.set(q, {
        id: `db-${i}`,
        q,
        a: item.a?.trim() || "",
        cat: guessFaqCategory(q),
      });
    }
  });
  return Array.from(byQ.values());
}
